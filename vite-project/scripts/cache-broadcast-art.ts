import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rename, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { allPoolHeroes as heroes } from '../src/shared/heroPool.js';

// Startup preparation runs before build/server; existing checked assets are reused.
// Never invoke this while a live match is running.
// Source URLs remain in the manifest so a data override cannot select stale art.
const root = fileURLToPath(new URL('../', import.meta.url));
const directory = resolve(root, 'public/heroesArt');
await mkdir(directory, { recursive: true });
const records: Record<string, { source: string; local: string }> = {};
const failures: string[] = [];
const existing = await readdir(directory);
const queue = heroes.filter((hero) => hero.artLink);
async function readArtwork(response: Response) {
  const reader = response.body?.getReader();
  if (!reader) throw new Error('Empty artwork response');
  const chunks: Uint8Array[] = [];
  let size = 0;
  try {
    while (true) {
      const chunk = await reader.read();
      if (chunk.done) break;
      size += chunk.value.byteLength;
      if (size > 8 * 1024 * 1024) throw new Error('Artwork too large');
      chunks.push(chunk.value);
    }
    return Buffer.concat(chunks);
  } catch (error) {
    await reader.cancel().catch(() => {});
    throw error;
  } finally {
    reader.releaseLock();
  }
}
let cursor = 0;
await Promise.all(
  Array.from({ length: 3 }, async () => {
    while (cursor < queue.length) {
      const hero = queue[cursor++],
        source = hero.artLink!;
      try {
        const sourceKey = createHash('sha256').update(source).digest('hex').slice(0, 12);
        const prefix = `broadcast-${hero.id}-${sourceKey}`;
        const cached = existing.find((name) => name.startsWith(prefix) && name.endsWith('.webp'));
        let output: Buffer;
        try {
          output = await readFile(resolve(directory, cached ?? `${prefix}.webp`));
          const meta = await sharp(output, { limitInputPixels: 32_000_000 }).metadata();
          if (
            meta.format !== 'webp' ||
            !meta.width ||
            !meta.height ||
            meta.width > 1600 ||
            meta.height > 1600
          )
            throw new Error('Cached artwork needs rebuilding');
        } catch {
          let bytes: Buffer;
          if (source.startsWith('/heroesArt/'))
            bytes = await readFile(resolve(root, `public${source}`));
          else {
            const url = new URL(source);
            if (
              url.protocol !== 'https:' ||
              !['world.honorofkings.com', 'camp.honorofkings.com'].includes(url.hostname) ||
              url.username ||
              url.password
            )
              throw new Error('Untrusted artwork source');
            const response = await fetch(source, {
              signal: AbortSignal.timeout(20000),
              redirect: 'error',
            });
            if (!response.ok) throw new Error(`HTTP ${response.status}`);
            if (Number(response.headers.get('content-length')) > 8 * 1024 * 1024)
              throw new Error('Artwork too large');
            bytes = await readArtwork(response);
          }
          if (bytes.length > 8 * 1024 * 1024) throw new Error('Artwork too large');
          output = await sharp(bytes, { limitInputPixels: 32_000_000 })
            .rotate()
            .resize(1600, 1600, { fit: 'inside', withoutEnlargement: true })
            .webp({ quality: 86, effort: 4 })
            .toBuffer();
        }
        const checksum = createHash('sha256').update(output).digest('hex').slice(0, 12);
        const name = `${prefix}-${checksum}.webp`;
        if (cached !== name) {
          await writeFile(resolve(directory, name), output);
          // Keep previous content-addressed files: an already open OBS page may still use them.
        }
        records[String(hero.id)] = { source, local: `/heroesArt/${name}` };
      } catch (error) {
        failures.push(`${hero.id}: ${String(error)}`);
      }
    }
  }),
);
// Always publish successful entries; missing sources retain the existing URL.
const manifest = resolve(root, 'src/data/broadcastArtAssets.ts');
const temporary = manifest + '.tmp';
await writeFile(
  temporary,
  '// Generated by npm run hero:art-cache. Original sources retained for attribution and invalidation.\n' +
    'const assets: Record<string, { source: string; local: string }> = ' +
    JSON.stringify(records, null, 2) +
    ';\nexport default assets;\n',
);
await rename(temporary, manifest);
console.log(`Cached ${Object.keys(records).length}/${queue.length} broadcast artworks.`);
if (failures.length) {
  console.error(failures.join('\n'));
  process.exitCode = 1;
}
