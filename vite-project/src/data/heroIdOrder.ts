export function migrateLegacyHeroId(id: number | null | undefined): number | null | undefined {
  if (id === null || id === undefined) return id;
  return legacyHeroIdToReleaseId[id] ?? id;
}

export function migrateLegacyHeroIdRecord<T>(record: Record<string, T> | undefined): Record<string, T> {
  if (!record) return {};
  return Object.fromEntries(
    Object.entries(record).map(([id, value]) => [String(migrateLegacyHeroId(Number(id))), value]),
  );
}
